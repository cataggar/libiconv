#!/usr/bin/env python3
"""Generates lib/aliases.h, lib/canonical.h, lib/canonical_local.h from the
output of genaliases.c (aliases.gperf, canonical.sh, canonical_local.sh),
WITHOUT needing the real `gperf` tool.

Upstream feeds aliases.gperf through `gperf -m 10` to get a perfect hash
table, then post-processes canonical.sh/canonical_local.sh (which grep
gperf's generated stringpool field names out of gperf's own output) to
build canonical.h/canonical_local.h. Since gperf isn't available here, this
builds the same *interface* (a global `stringpool` char array + `aliases[]`
array of {offset-into-stringpool, encoding_index} + an `aliases_lookup`
function with the exact signature iconv.c expects, see the comment above
its `#include "aliases.h"`) using a plain linear scan instead of a perfect
hash. Correct, just O(n) instead of O(1) per lookup -- fine for a one-time
iconv_open() call.
"""
import re
import sys
from pathlib import Path

LIB = Path(__file__).resolve().parent


def parse_aliases_gperf(path):
    """Returns list of (ALIAS_NAME, ei_symbol) in file order."""
    entries = []
    in_body = False
    for line in path.read_text().splitlines():
        if line.strip() == "%%":
            in_body = True
            continue
        if not in_body or not line.strip():
            continue
        name, ei = line.split(",", 1)
        entries.append((name.strip(), ei.strip()))
    return entries


def parse_canonical_sh(path):
    """Returns the ordered list of canonical (primary) alias names, one per
    encoding, extracted from each line's `grep 'sizeof("NAME")'`."""
    names = []
    pattern = re.compile(r'sizeof\("([^"]*)"\)')
    for line in path.read_text().splitlines():
        if not line.strip():
            continue
        m = pattern.search(line)
        if not m:
            raise SystemExit(f"could not parse line: {line!r}")
        names.append(m.group(1))
    return names


def build_stringpool(alias_entries):
    """Concatenates each unique alias name (NUL-terminated) into one pool,
    returns (pool_bytes, {name: offset})."""
    pool = bytearray()
    offsets = {}
    for name, _ei in alias_entries:
        if name not in offsets:
            offsets[name] = len(pool)
            pool += name.encode("ascii") + b"\x00"
    return bytes(pool), offsets


def c_byte_array_lines(data, width=20):
    """Emits a plain decimal byte-array initializer, chunked for readability
    (avoids any ambiguity/greedy-parsing pitfalls of C string-literal hex
    escapes)."""
    lines = []
    for i in range(0, len(data), width):
        chunk = data[i : i + width]
        lines.append("  " + ", ".join(str(b) for b in chunk))
    return lines


def main():
    aliases_entries = parse_aliases_gperf(LIB / "aliases.gperf")
    pool, offsets = build_stringpool(aliases_entries)

    with (LIB / "aliases.h").open("w", newline="\n") as f:
        f.write(
            "/* Generated by gen-aliases-header.py (gperf replacement); "
            "see that script for details. */\n\n"
        )
        f.write("struct alias { int name; unsigned int encoding_index; };\n\n")
        max_word_length = max(len(name) for name, _ei in aliases_entries)
        f.write(f"#define MAX_WORD_LENGTH {max_word_length}\n")
        f.write(f"#define aliases_stringpool_size {len(pool)}\n")
        f.write("static const char aliases_stringpool[aliases_stringpool_size] = {\n")
        f.write(",\n".join(c_byte_array_lines(pool)))
        f.write("\n};\n")
        f.write("#define stringpool aliases_stringpool\n\n")
        f.write(f"static const struct alias aliases[{len(aliases_entries)}] =\n{{\n")
        for name, ei in aliases_entries:
            f.write(f"  {{ {offsets[name]}, {ei} }},\n")
        f.write("};\n\n")
        f.write(
            "static const struct alias *\n"
            "aliases_lookup (const char *str, unsigned int len)\n"
            "{\n"
            "  unsigned int i;\n"
            "  for (i = 0; i < sizeof(aliases)/sizeof(aliases[0]); i++)\n"
            "    {\n"
            "      const char *name = stringpool + aliases[i].name;\n"
            "      if (name[len] == '\\0' && memcmp(name, str, len) == 0)\n"
            "        return &aliases[i];\n"
            "    }\n"
            "  return NULL;\n"
            "}\n"
        )

    for sh_name, h_name in (
        ("canonical.sh", "canonical.h"),
        ("canonical_local.sh", "canonical_local.h"),
    ):
        canon_names = parse_canonical_sh(LIB / sh_name)
        with (LIB / h_name).open("w", newline="\n") as f:
            f.write(f"/* Generated by gen-aliases-header.py from {sh_name}. */\n")
            for name in canon_names:
                if name not in offsets:
                    raise SystemExit(f"{h_name}: {name!r} not found in aliases.gperf")
                f.write(f"  {offsets[name]},\n")

    print(f"wrote aliases.h ({len(aliases_entries)} aliases, {len(pool)}-byte pool), "
          f"canonical.h, canonical_local.h")


if __name__ == "__main__":
    sys.exit(main())
